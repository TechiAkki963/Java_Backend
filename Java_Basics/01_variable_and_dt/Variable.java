class Varaiable
{
    public static void main(String args[]){

        byte b = 5;
        System.out.println(b);

        // b = 225;
        // System.out.println(b);

        short s = 225;
        System.out.println(s);

        int i = 3000;
        System.out.println(i);

        float f = 300.25f;
        System.out.println(f);

        char c = 'a';
        System.out.println(c);


    }


}

// Variable - Naming Rules
// Case Sensitive
// Contains Alphabet , Number, _ or $
// can start with _ or $
// Should not be keywords
// Should not be class name, if class is also in use
// No limits on Length of Name
// Follow Camel Cases

